import type { Runtime } from '../Runtime.js'

export const CLUSTER_DOCUMENT_ID = '_design/cluster'

export type NodeRole = 'orchestrator' | 'member'

/** What a node says about itself. The orchestrator records it in the cluster document. */
export interface NodeAnnouncement {
  /** Chosen by the user; defaults to the host name on Node.js and to browser and OS in a browser. */
  readonly name: string
  readonly runtime: Runtime
  readonly coreVersion: string
  /** Ids of the capabilities the node can perform now, e.g. `fetch@1`: runtime, setup and permissions decide. */
  readonly capabilities: readonly string[]
  readonly userAgent?: string
  readonly os?: string
  /** Where other nodes reach this node, once it serves. */
  readonly endpoint?: string
}

export interface ClusterNode extends NodeAnnouncement {
  /** Generated by the orchestrator when the node joins, or by the founding node itself. */
  readonly id: string
  readonly role: NodeRole
  readonly joinedAt: string
  readonly announcedAt: string
}

export interface ClusterDocument {
  readonly _id: typeof CLUSTER_DOCUMENT_ID
  readonly _rev?: string
  readonly dataset: string
  readonly nodes: readonly ClusterNode[]
}

export function newClusterDocument(datasetId: string, founder: ClusterNode): ClusterDocument {
  return { _id: CLUSTER_DOCUMENT_ID, dataset: datasetId, nodes: [founder] }
}

export function newNode(id: string, role: NodeRole, announcement: NodeAnnouncement, now: Date): ClusterNode {
  const at = now.toISOString()
  return { ...announcement, id, role, joinedAt: at, announcedAt: at }
}

export function withNode(document: ClusterDocument, node: ClusterNode): ClusterDocument {
  return { ...document, nodes: [...document.nodes.filter((existing) => existing.id !== node.id), node] }
}

/**
 * Applies a node's announcement. An announcement without an endpoint keeps the one on record: a server
 * that restarted is still reachable there once it serves again.
 */
export function withAnnouncement(document: ClusterDocument, nodeId: string, announcement: NodeAnnouncement, now: Date): ClusterDocument {
  return {
    ...document,
    nodes: document.nodes.map((node) => {
      if (node.id !== nodeId) return node
      const endpoint = announcement.endpoint ?? node.endpoint
      const { endpoint: _, ...rest } = announcement
      return {
        ...rest,
        ...(endpoint === undefined ? {} : { endpoint }),
        id: node.id,
        role: node.role,
        joinedAt: node.joinedAt,
        announcedAt: now.toISOString(),
      }
    }),
  }
}

/** Whether recording the announcement would change anything besides its timestamp. */
export function announcementChanges(node: ClusterNode, announcement: NodeAnnouncement): boolean {
  return (
    node.name !== announcement.name ||
    node.runtime !== announcement.runtime ||
    node.coreVersion !== announcement.coreVersion ||
    node.userAgent !== announcement.userAgent ||
    node.os !== announcement.os ||
    (announcement.endpoint !== undefined && node.endpoint !== announcement.endpoint) ||
    node.capabilities.join(',') !== [...announcement.capabilities].sort().join(',')
  )
}

/** Validates an announcement received from another node. Throws TypeError naming the first problem. */
export function parseAnnouncement(value: unknown): NodeAnnouncement {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) throw new TypeError('An announcement must be an object')
  const candidate = value as Record<string, unknown>
  if (typeof candidate.name !== 'string' || candidate.name.trim() === '' || candidate.name.length > 200) {
    throw new TypeError('A node needs a name of 1 to 200 characters')
  }
  if (candidate.runtime !== 'nodejs' && candidate.runtime !== 'browser') throw new TypeError('Unknown runtime')
  if (typeof candidate.coreVersion !== 'string') throw new TypeError('A node must announce its core version')
  if (!Array.isArray(candidate.capabilities) || !candidate.capabilities.every(isCapabilityId)) {
    throw new TypeError('Capabilities must be a list of capability ids')
  }
  for (const field of ['userAgent', 'os', 'endpoint'] as const) {
    if (candidate[field] !== undefined && typeof candidate[field] !== 'string') throw new TypeError(`${field} must be a string`)
  }
  if (typeof candidate.endpoint === 'string') {
    const protocol = new URL(candidate.endpoint).protocol
    if (protocol !== 'http:' && protocol !== 'https:') throw new TypeError('An endpoint must be an http or https URL')
  }
  return {
    name: candidate.name.trim(),
    runtime: candidate.runtime,
    coreVersion: candidate.coreVersion,
    capabilities: [...new Set(candidate.capabilities as string[])].sort(),
    ...(typeof candidate.userAgent === 'string' ? { userAgent: candidate.userAgent } : {}),
    ...(typeof candidate.os === 'string' ? { os: candidate.os } : {}),
    ...(typeof candidate.endpoint === 'string' ? { endpoint: candidate.endpoint } : {}),
  }
}

export function isClusterDocument(value: unknown): value is ClusterDocument {
  if (typeof value !== 'object' || value === null) return false
  const candidate: { _id?: unknown; dataset?: unknown; nodes?: unknown } = value
  return (
    candidate._id === CLUSTER_DOCUMENT_ID &&
    typeof candidate.dataset === 'string' &&
    Array.isArray(candidate.nodes) &&
    candidate.nodes.every(isClusterNode)
  )
}

function isClusterNode(value: unknown): value is ClusterNode {
  if (typeof value !== 'object' || value === null) return false
  const candidate = value as Record<string, unknown>
  return (
    typeof candidate.id === 'string' &&
    typeof candidate.name === 'string' &&
    (candidate.runtime === 'nodejs' || candidate.runtime === 'browser') &&
    (candidate.role === 'orchestrator' || candidate.role === 'member') &&
    typeof candidate.coreVersion === 'string' &&
    Array.isArray(candidate.capabilities) &&
    candidate.capabilities.every(isCapabilityId) &&
    typeof candidate.joinedAt === 'string' &&
    typeof candidate.announcedAt === 'string' &&
    optionalString(candidate.userAgent) &&
    optionalString(candidate.os) &&
    optionalString(candidate.endpoint)
  )
}

function isCapabilityId(value: unknown): value is string {
  return typeof value === 'string' && /^[a-z][a-z0-9-]*@[1-9]\d*$/.test(value)
}

function optionalString(value: unknown): boolean {
  return value === undefined || typeof value === 'string'
}
